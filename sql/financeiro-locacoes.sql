-- Run after marketplace-admin.sql in Supabase SQL Editor.
-- This stores rental terms for finance tracking only. Signed agreements remain
-- outside the application and are handled by the administrator over WhatsApp.

create table if not exists public.despesas (
  id bigint generated by default as identity primary key,
  titulo text not null,
  valor numeric(10,2) not null default 0.00,
  categoria text not null,
  tipo text not null,
  status text default 'Pendente',
  mes_referencia text not null
);

alter table public.inquilinos
  add column if not exists nascimento date,
  add column if not exists cpf text,
  add column if not exists rg text,
  add column if not exists rg_data_expedicao date,
  add column if not exists estado_civil text,
  add column if not exists profissao text,
  add column if not exists email text,
  add column if not exists empresa_trabalho text,
  add column if not exists endereco text;

alter table public.despesas
  add column if not exists data_vencimento date,
  add column if not exists data_pagamento date,
  add column if not exists ratear boolean not null default false,
  add column if not exists atualizado_em timestamptz not null default now();

create table if not exists public.locacoes (
  id bigint generated by default as identity primary key,
  inquilino_id bigint not null references public.inquilinos(id) on delete restrict,
  quarto_id bigint not null references public.quartos(id) on delete restrict,
  modalidade text not null check (modalidade in ('mensal', 'diaria')),
  data_inicio date not null,
  data_fim date not null,
  valor numeric(10,2) not null check (valor > 0),
  dia_vencimento integer not null default 10 check (dia_vencimento between 1 and 31),
  taxa_contrato numeric(10,2) not null default 0 check (taxa_contrato >= 0),
  forma_pagamento text not null default 'pix' check (forma_pagamento in ('pix', 'dinheiro', 'outro')),
  despesas_regra text not null default 'incluidas' check (despesas_regra in ('incluidas', 'rateio', 'outra')),
  despesas_descricao text,
  multa_percentual numeric(6,3) not null default 0 check (multa_percentual >= 0),
  juros_percentual numeric(6,3) not null default 0 check (juros_percentual >= 0),
  aviso_rescisao_dias integer not null default 30 check (aviso_rescisao_dias between 0 and 365),
  fiador_nome text,
  fiador_nascimento date,
  fiador_cpf text,
  fiador_rg text,
  fiador_telefone text,
  fiador_estado_civil text,
  fiador_profissao text,
  fiador_endereco text,
  fiador_conjuge_nome text,
  fiador_conjuge_cpf text,
  status text not null default 'ativa' check (status in ('ativa', 'encerrada', 'cancelada')),
  criada_em timestamptz not null default now(),
  encerrada_em timestamptz,
  constraint locacoes_datas_validas check (data_fim > data_inicio)
);

create index if not exists locacoes_status_datas_idx
  on public.locacoes (status, data_inicio, data_fim);
create index if not exists locacoes_inquilino_idx
  on public.locacoes (inquilino_id, status);
create index if not exists locacoes_quarto_idx
  on public.locacoes (quarto_id, status);

-- Monthly checkout dates stay occupied; daily checkout dates are available.
create or replace function public.quarto_ocupado_hoje(p_quarto_id bigint)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.locacoes as locacao
    join public.quartos as quarto
      on quarto.id = locacao.quarto_id
    join public.casas as casa
      on casa.id = quarto.casa_id
    where locacao.quarto_id = p_quarto_id
      and locacao.status = 'ativa'
      and quarto.disponivel = true
      and casa.disponivel = true
      and locacao.data_inicio <= timezone('America/Sao_Paulo', now())::date
      and case
        when locacao.modalidade = 'diaria' then
          locacao.data_fim > timezone('America/Sao_Paulo', now())::date
        else locacao.data_fim >= timezone('America/Sao_Paulo', now())::date
      end
  );
$$;

revoke all on function public.quarto_ocupado_hoje(bigint) from public;
grant execute on function public.quarto_ocupado_hoje(bigint) to anon, authenticated;

do $$
declare
  policy_row record;
begin
  for policy_row in
    select policyname
    from pg_policies
    where schemaname = 'public'
      and tablename = 'quartos'
      and cmd in ('SELECT', 'ALL')
  loop
    execute format('drop policy %I on public.quartos', policy_row.policyname);
  end loop;
end
$$;

create policy "Public can read available rooms"
  on public.quartos for select
  to anon, authenticated
  using (
    disponivel = true
    and not public.quarto_ocupado_hoje(id)
    and exists (
      select 1
      from public.casas
      where casas.id = quartos.casa_id
        and casas.disponivel = true
    )
  );

create policy "Administrators manage rooms"
