create or replace function public.criar_locacao_financeira(p_inquilino jsonb, p_locacao jsonb)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_inquilino_id bigint;
  v_locacao_id bigint;
  v_modalidade text;
  v_data_inicio date;
  v_data_fim date;
  v_valor numeric(10,2);
  v_dia_vencimento integer;
  v_taxa numeric(10,2);
  v_mes date;
  v_periodo_inicio date;
  v_periodo_fim date;
  v_vencimento date;
  v_dias_mes integer;
  v_dias_ocupados integer;
  v_cobrancas integer := 0;
begin
  if not public.is_pensionato_admin() then
    raise exception 'Apenas um administrador pode criar locações.';
  end if;
  if nullif(trim(p_inquilino ->> 'nome'), '') is null
    or nullif(trim(p_inquilino ->> 'telefone'), '') is null then
    raise exception 'Nome e telefone do inquilino são obrigatórios.';
  end if;
  if nullif(p_locacao ->> 'quarto_id', '') is null then
    raise exception 'Selecione o quarto da locação.';
  end if;

  v_modalidade := p_locacao ->> 'modalidade';
  v_data_inicio := (p_locacao ->> 'data_inicio')::date;
  v_data_fim := (p_locacao ->> 'data_fim')::date;
  v_valor := (p_locacao ->> 'valor')::numeric;
  v_dia_vencimento := coalesce(nullif(p_locacao ->> 'dia_vencimento', '')::integer, 10);
  v_taxa := coalesce(nullif(p_locacao ->> 'taxa_contrato', '')::numeric, 0);

  if v_modalidade not in ('mensal', 'diaria') or v_data_fim <= v_data_inicio or v_valor <= 0 then
    raise exception 'Confira modalidade, período e valor da locação.';
  end if;
  if v_modalidade = 'mensal' and v_dia_vencimento not between 1 and 31 then
    raise exception 'O vencimento mensal deve ser entre os dias 1 e 31.';
  end if;
  if v_modalidade = 'diaria' and v_data_fim - v_data_inicio < 1 then
    raise exception 'A locação diária precisa ter ao menos uma noite.';
  end if;

  perform pg_advisory_xact_lock((p_locacao ->> 'quarto_id')::bigint);

  if exists (
    select 1
    from public.locacoes as locacao
    where locacao.quarto_id = (p_locacao ->> 'quarto_id')::bigint
      and locacao.status = 'ativa'
      and locacao.data_inicio < case
        when v_modalidade = 'mensal' then v_data_fim + 1
        else v_data_fim
      end
      and (case
        when locacao.modalidade = 'mensal' then locacao.data_fim + 1
        else locacao.data_fim
      end) > v_data_inicio
  ) then
    raise exception 'Este quarto já possui uma locação para parte ou todo o período informado.';
  end if;

  insert into public.inquilinos (
    nome, telefone, email, nascimento, cpf, rg, rg_data_expedicao,
    estado_civil, profissao, empresa_trabalho, endereco,
    valor_aluguel, dia_vencimento, leito_id
  )
  values (
    trim(p_inquilino ->> 'nome'),
    trim(p_inquilino ->> 'telefone'),
    nullif(trim(p_inquilino ->> 'email'), ''),
    nullif(p_inquilino ->> 'nascimento', '')::date,
    nullif(trim(p_inquilino ->> 'cpf'), ''),
    nullif(trim(p_inquilino ->> 'rg'), ''),
    nullif(p_inquilino ->> 'rg_data_expedicao', '')::date,
    nullif(trim(p_inquilino ->> 'estado_civil'), ''),
    nullif(trim(p_inquilino ->> 'profissao'), ''),
    nullif(trim(p_inquilino ->> 'empresa_trabalho'), ''),
    nullif(trim(p_inquilino ->> 'endereco'), ''),
    v_valor,
    v_dia_vencimento,
    null
  )
  returning id into v_inquilino_id;

  insert into public.locacoes (
    inquilino_id, quarto_id, modalidade, data_inicio, data_fim, valor,
    dia_vencimento, taxa_contrato, forma_pagamento, despesas_regra,
    despesas_descricao, multa_percentual, juros_percentual, aviso_rescisao_dias,
    fiador_nome, fiador_nascimento, fiador_cpf, fiador_rg, fiador_telefone,
    fiador_estado_civil, fiador_profissao, fiador_endereco,
    fiador_conjuge_nome, fiador_conjuge_cpf
  )
  values (
    v_inquilino_id,
    (p_locacao ->> 'quarto_id')::bigint,
    v_modalidade,
    v_data_inicio,
    v_data_fim,
    v_valor,
    v_dia_vencimento,
    v_taxa,
    coalesce(nullif(p_locacao ->> 'forma_pagamento', ''), 'pix'),
    coalesce(nullif(p_locacao ->> 'despesas_regra', ''), 'incluidas'),
    nullif(trim(p_locacao ->> 'despesas_descricao'), ''),
    coalesce(nullif(p_locacao ->> 'multa_percentual', '')::numeric, 0),
    coalesce(nullif(p_locacao ->> 'juros_percentual', '')::numeric, 0),
    coalesce(nullif(p_locacao ->> 'aviso_rescisao_dias', '')::integer, 30),
    nullif(trim(p_locacao ->> 'fiador_nome'), ''),
    nullif(p_locacao ->> 'fiador_nascimento', '')::date,
    nullif(trim(p_locacao ->> 'fiador_cpf'), ''),
    nullif(trim(p_locacao ->> 'fiador_rg'), ''),
    nullif(trim(p_locacao ->> 'fiador_telefone'), ''),
    nullif(trim(p_locacao ->> 'fiador_estado_civil'), ''),
    nullif(trim(p_locacao ->> 'fiador_profissao'), ''),
    nullif(trim(p_locacao ->> 'fiador_endereco'), ''),
    nullif(trim(p_locacao ->> 'fiador_conjuge_nome'), ''),
    nullif(trim(p_locacao ->> 'fiador_conjuge_cpf'), '')
  )
  returning id into v_locacao_id;

  if v_modalidade = 'mensal' then
    v_mes := date_trunc('month', v_data_inicio)::date;
    while v_mes <= date_trunc('month', v_data_fim)::date loop
      v_periodo_inicio := greatest(v_data_inicio, v_mes);
      v_periodo_fim := least(v_data_fim, (v_mes + interval '1 month - 1 day')::date);
      v_dias_mes := extract(day from (v_mes + interval '1 month - 1 day'))::integer;
      v_dias_ocupados := v_periodo_fim - v_periodo_inicio + 1;
      v_vencimento := make_date(
        extract(year from v_mes)::integer,
        extract(month from v_mes)::integer,
        least(v_dia_vencimento, v_dias_mes)
      );
      if v_mes = date_trunc('month', v_data_inicio)::date then
        v_vencimento := greatest(v_vencimento, v_data_inicio);
      end if;

      insert into public.recebimentos (
        locacao_id, inquilino_id, categoria, descricao, valor, data_vencimento,
        mes_referencia, forma_pagamento, chave_unica
      )
      values (
        v_locacao_id, v_inquilino_id, 'aluguel',
        'Aluguel mensal - ' || to_char(v_mes, 'MM/YYYY'),
        round(v_valor * v_dias_ocupados / v_dias_mes, 2),
        v_vencimento,
        to_char(v_mes, 'YYYY-MM'),
        coalesce(nullif(p_locacao ->> 'forma_pagamento', ''), 'pix'),
        'locacao:' || v_locacao_id || ':aluguel:' || to_char(v_mes, 'YYYY-MM')
      );
      v_cobrancas := v_cobrancas + 1;
      v_mes := (v_mes + interval '1 month')::date;
    end loop;
  else
    insert into public.recebimentos (
      locacao_id, inquilino_id, categoria, descricao, valor, data_vencimento,
      mes_referencia, forma_pagamento, chave_unica
    )
    values (
      v_locacao_id, v_inquilino_id, 'diaria',
      'Estadia de ' || (v_data_fim - v_data_inicio)::text || ' noites',
      round(v_valor * (v_data_fim - v_data_inicio), 2),
      v_data_inicio,
      to_char(v_data_inicio, 'YYYY-MM'),
      coalesce(nullif(p_locacao ->> 'forma_pagamento', ''), 'pix'),
      'locacao:' || v_locacao_id || ':diaria'
    );
    v_cobrancas := 1;
  end if;

  if v_taxa > 0 then
    insert into public.recebimentos (
      locacao_id, inquilino_id, categoria, descricao, valor, data_vencimento,
      mes_referencia, forma_pagamento, chave_unica
    )
    values (
      v_locacao_id, v_inquilino_id, 'taxa_contrato', 'Taxa de contrato',
      v_taxa, v_data_inicio, to_char(v_data_inicio, 'YYYY-MM'),
      coalesce(nullif(p_locacao ->> 'forma_pagamento', ''), 'pix'),
      'locacao:' || v_locacao_id || ':taxa_contrato'
    );
    v_cobrancas := v_cobrancas + 1;
  end if;

  return jsonb_build_object(
    'locacao_id', v_locacao_id,
    'inquilino_id', v_inquilino_id,
    'cobrancas_geradas', v_cobrancas
  );
end;
$$;

create or replace function public.registrar_despesa_financeira(p_despesa jsonb)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_despesa_id bigint;
  v_valor numeric(10,2);
  v_vencimento date;
  v_data_pagamento date;
  v_status text;
  v_ratear boolean;
  v_count integer := 0;
  v_base numeric(10,2);
  v_sobra numeric(10,2);
  v_rateio numeric(10,2);
  v_locacao record;
  v_index integer := 0;
begin
  if not public.is_pensionato_admin() then
    raise exception 'Apenas um administrador pode registrar despesas.';
  end if;

  if nullif(trim(p_despesa ->> 'titulo'), '') is null
    or nullif(trim(p_despesa ->> 'categoria'), '') is null
    or nullif(trim(p_despesa ->> 'tipo'), '') is null then
    raise exception 'Descrição, categoria e tipo da despesa são obrigatórios.';
  end if;

  v_valor := (p_despesa ->> 'valor')::numeric;
  v_vencimento := (p_despesa ->> 'data_vencimento')::date;
  v_status := coalesce(nullif(p_despesa ->> 'status', ''), 'Pendente');
  v_ratear := coalesce((p_despesa ->> 'ratear')::boolean, false);
  v_data_pagamento := nullif(p_despesa ->> 'data_pagamento', '')::date;
  if v_status = 'Pago' and v_data_pagamento is null then
    v_data_pagamento := current_date;
  end if;

  if v_valor <= 0 or v_status not in ('Pendente', 'Pago') then
    raise exception 'Confira o valor e o status da despesa.';
  end if;

  insert into public.despesas (
    titulo, valor, categoria, tipo, status, mes_referencia,
    data_vencimento, data_pagamento, ratear, atualizado_em
  )
  values (
    trim(p_despesa ->> 'titulo'),
    v_valor,
    p_despesa ->> 'categoria',
    p_despesa ->> 'tipo',
    v_status,
    to_char(v_vencimento, 'YYYY-MM'),
    v_vencimento,
    v_data_pagamento,
    v_ratear,
    now()
  )
  returning id into v_despesa_id;

  if v_ratear then
    select count(*) into v_count
    from public.locacoes
    where status = 'ativa'
      and despesas_regra = 'rateio'
      and data_inicio <= v_vencimento
      and (
        (modalidade = 'mensal' and data_fim >= v_vencimento)
        or (modalidade = 'diaria' and data_fim > v_vencimento)
      );

    if v_count > 0 then
      v_base := trunc(v_valor / v_count, 2);
      v_sobra := v_valor - (v_base * v_count);
      for v_locacao in
        select locacoes.id, locacoes.inquilino_id
        from public.locacoes
        where status = 'ativa'
          and despesas_regra = 'rateio'
          and data_inicio <= v_vencimento
          and (
            (modalidade = 'mensal' and data_fim >= v_vencimento)
            or (modalidade = 'diaria' and data_fim > v_vencimento)
          )
        order by locacoes.id
      loop
        v_index := v_index + 1;
        v_rateio := v_base;
        if v_index = 1 then
          v_rateio := v_rateio + v_sobra;
        end if;

        insert into public.recebimentos (
          locacao_id, inquilino_id, categoria, descricao, valor,
          data_vencimento, mes_referencia, chave_unica
        )
        values (
          v_locacao.id,
          v_locacao.inquilino_id,
          'rateio',
          'Rateio: ' || trim(p_despesa ->> 'titulo'),
          v_rateio,
          v_vencimento,
          to_char(v_vencimento, 'YYYY-MM'),
          'despesa:' || v_despesa_id || ':locacao:' || v_locacao.id
        );
      end loop;
    end if;
  end if;

  return jsonb_build_object(
    'despesa_id', v_despesa_id,
    'locacoes_rateadas', v_count
  );
end;
$$;

create or replace function public.encerrar_locacao_financeira(
  p_locacao_id bigint,
  p_data_corte date default current_date
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_locacoes_atualizadas integer;
  v_cobrancas_canceladas integer;
begin
  if not public.is_pensionato_admin() then
    raise exception 'Apenas um administrador pode encerrar locações.';
  end if;
  if p_locacao_id is null or p_data_corte is null then
    raise exception 'Informe a locação e a data de encerramento.';
  end if;

  update public.locacoes
  set status = 'encerrada',
      encerrada_em = now()
  where id = p_locacao_id
    and status = 'ativa';
  get diagnostics v_locacoes_atualizadas = row_count;

  if v_locacoes_atualizadas = 0 then
    raise exception 'A locação não foi encontrada ou já foi encerrada.';
  end if;

  update public.recebimentos
  set status = 'Cancelado',
      atualizado_em = now()
  where locacao_id = p_locacao_id
    and status = 'Pendente'
    and data_vencimento > p_data_corte;
  get diagnostics v_cobrancas_canceladas = row_count;

  return jsonb_build_object(
    'cobrancas_canceladas', v_cobrancas_canceladas
  );
end;
$$;

