  id bigint generated by default as identity primary key,
  locacao_id bigint references public.locacoes(id) on delete set null,
  inquilino_id bigint references public.inquilinos(id) on delete set null,
  categoria text not null check (categoria in ('aluguel', 'diaria', 'taxa_contrato', 'rateio', 'outro')),
  descricao text not null,
  valor numeric(10,2) not null check (valor >= 0),
  data_vencimento date not null,
  mes_referencia text not null,
  status text not null default 'Pendente' check (status in ('Pendente', 'Pago', 'Cancelado')),
  data_pagamento date,
  forma_pagamento text check (forma_pagamento in ('pix', 'dinheiro', 'outro')),
  chave_unica text unique,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
